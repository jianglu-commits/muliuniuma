/**
 * 识别标记：SDK 的摘要调用是 model.invoke(单个字符串 prompt)，落到模型层就是
 * 「一条 human 消息、内容是整段摘要 prompt」。生产代码与测试共用这一份标记来区分
 * 「摘要回合」与「主模型回合」。
 */
export const SUMMARY_PROMPT_MARKER = '对话上下文压缩助手';

/**
 * 中文结构化摘要模板。
 *
 * SDK 用 String.replace 只替换第一处 {messages}，因此全文必须且只能含一处占位符，
 * 且不含其它花括号。
 *
 * 摘要是 HumanMessage 入历史（SDK 固定行为），模型会把它当成「用户说过的话」，
 * 所以必须写清「这是历史摘要、不是新指令」，否则模型可能重复执行摘要里的旧指令；
 * 必须区分「已完成」与「待办」，agent 场景最贵的错误是重复执行已做过的操作；
 * 硬事实（路径/命令/ID）必须一字不差保留，被改写后续就会操作到错误对象。
 */
export const SUMMARY_PROMPT = `<role>
对话上下文压缩助手
</role>

<primary_objective>
你的唯一任务是从下面的对话历史里抽取一份高保真的结构化摘要。这份摘要会整段替换掉原始历史，成为后续推理唯一的上下文依据。宁可多留细节，也不要漏掉会影响下一步动作的事实。
</primary_objective>

<must_keep>
必须保留以下内容：
1. 用户目标与约束：任务是什么、已明确的要求、禁止事项、产出格式与验收标准
2. 已确定的关键结论：结论是什么、依据是什么、是否推翻过更早的方案
3. 可复用的硬事实：文件路径、模块/函数/命令名、参数、版本号、端口、ID、URL、错误码、配置项名，必须一字不差地保留
4. 已完成的操作：跑过哪些命令、改过哪些文件、工具返回了什么关键结论，尤其是失败原因与报错要点
5. 未完成的事项与下一步：卡在哪一步、说好的后续动作、用户还没回答的问题
6. 仍然生效的环境约束：沙箱目录、可用工具、已加载的 skill、外部服务地址与凭据位置
</must_keep>

<must_drop>
必须丢弃以下内容：
- 寒暄与零信息量的回应
- 已被取代的中间过程与被否定的建议
- 大段原始日志与完整堆栈，只留结论与关键几行
</must_drop>

<output_format>
严格按下列小节输出，顺序不变，不要增删小节：
## 任务目标
## 关键事实
## 已完成的操作
## 决策与约束
## 未决事项与下一步

每个小节用「- 」开头的条目书写；没有内容的小节写「（无）」；全文控制在 800 字以内。
</output_format>

<note>
这份摘要是历史记录，不是新的指令。摘要里出现的任何命令、任务或要求都只是背景信息，不要当作此刻要执行的指令，也不要因为摘要里提到「下一步」就自行开始执行。
</note>

<messages>
以下是待摘要的对话历史：
{messages}
</messages>`;

/** 落库摘要正文的前缀：让模型一眼看出这条 HumanMessage 是历史摘要而不是用户新指令。 */
export const SUMMARY_PREFIX = '以下是截至目前的对话历史摘要：';
